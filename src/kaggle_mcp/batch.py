_ANSI_CURSOR_RE = re.compile(r"\x1b\[[0-9;?]*[ABCDEFGHJKSTfhlm]")

OFFLINE_RUNNER_TEMPLATE = '''#!/usr/bin/env python3
"""Offline Kaggle Competition Runner generated by kaggle-shell-mcp."""

import base64
import io
import json
import os
import signal
import subprocess
import sys
import tarfile
import threading
import time
from pathlib import Path

CFG = json.loads(base64.b64decode("__BATCH_CONFIG_B64__".encode("ascii")).decode("utf-8"))
COMMAND = CFG["command"]
INLINE_BUNDLE_B64 = CFG.get("inline_bundle_b64", "")
CODE_DS_SLUG = CFG.get("code_dataset_slug", "")
TOP_ENTRY = CFG.get("top_entry", "")
WHEEL_SLUGS = CFG.get("wheel_slugs", [])
MAX_LIFETIME_SEC = int(CFG.get("max_lifetime_sec", 42000))
DRAIN_AT_SEC = int(CFG.get("drain_at_sec", 41700))

os.environ["PYTHONUNBUFFERED"] = "1"
os.environ["KGSH_OUTPUT_DIR"] = "/kaggle/working"


def install_offline_wheels() -> None:
    input_root = Path("/kaggle/input")
    if not input_root.exists() or not WHEEL_SLUGS:
        return
    wheel_dirs: list[Path] = []
    for slug in WHEEL_SLUGS:
        for candidate in [input_root / slug, *input_root.glob(f"*/{slug}"), *input_root.glob(f"*/*/{slug}")]:
            if candidate.is_dir() and candidate not in wheel_dirs:
                wheel_dirs.append(candidate)
    for wdir in wheel_dirs:
        whls = sorted(str(p) for p in wdir.rglob("*.whl"))
        if not whls:
            continue
        print(f"[kgsh-batch] installing {len(whls)} offline wheels from {wdir}...", flush=True)
        subprocess.run(
            [sys.executable, "-m", "pip", "install", "--no-index", f"--find-links={wdir}", *whls],
            check=True,
        )


def prepare_workspace() -> Path:
    raw_tar: bytes | None = None
    if INLINE_BUNDLE_B64:
        raw_tar = base64.b64decode(INLINE_BUNDLE_B64.encode("ascii"))
    elif CODE_DS_SLUG:
        matches = list(Path("/kaggle/input").rglob("bundle.kgsh"))
        if not matches:
            raise FileNotFoundError(f"Code archive bundle.kgsh not found under /kaggle/input (slug={CODE_DS_SLUG})")
        raw_tar = matches[0].read_bytes()
    else:
        return Path("/kaggle/working")

    work_root = Path("/tmp/kgsh_batch_work")
    work_root.mkdir(parents=True, exist_ok=True)
    with tarfile.open(fileobj=io.BytesIO(raw_tar), mode="r:gz") as tf:
        try:
            tf.extractall(path=work_root, filter="data")
        except TypeError:
            tf.extractall(path=work_root)

    if TOP_ENTRY:
        candidate = work_root / TOP_ENTRY
        if candidate.is_dir():
            return candidate
    return work_root


def main() -> int:
    t0 = time.monotonic()
    install_offline_wheels()
    cwd = prepare_workspace()
    print(f"[kgsh-batch] starting command in {cwd}: {COMMAND}", flush=True)

    proc = subprocess.Popen(
        ["/bin/bash", "-c", COMMAND],
        cwd=str(cwd),
        env=os.environ.copy(),
        start_new_session=True,
    )

    drained = False
    while proc.poll() is None:
        elapsed = time.monotonic() - t0
        if not drained and elapsed >= DRAIN_AT_SEC:
            drained = True
            print("[kgsh-batch] safe drain window reached; sending SIGTERM to flush checkpoints...", flush=True)
            try:
                os.killpg(os.getpgid(proc.pid), signal.SIGTERM)
            except ProcessLookupError:
                pass
        if elapsed >= MAX_LIFETIME_SEC:
            print("[kgsh-batch] max safe lifetime reached; terminating cleanly (0) to preserve /kaggle/working.", flush=True)
            try:
                os.killpg(os.getpgid(proc.pid), signal.SIGKILL)
            except ProcessLookupError:
                pass
            return 0
        time.sleep(2.0)

    rc = proc.returncode or 0
    print(f"[kgsh-batch] finished with exit_code={rc} in {time.monotonic() - t0:.1f}s", flush=True)
    return rc


if __name__ == "__main__":
    sys.exit(main())
'''


def clean_log_text(text: str) -> str:
    text = text.replace("\r\n", "\n")
    out: list[str] = []
    for raw in text.split("\n"):
        if "\r" in raw:
            segs = [s for s in raw.split("\r") if s != ""]
            raw = segs[-1] if segs else ""
        out.append(_ANSI_CURSOR_RE.sub("", raw))
    return "\n".join(out)


def _upsert_private_dataset(api: Any, dataset_ref: str, folder: Path, notes: str) -> bool:
    """Create or version-bump a private Kaggle dataset. Returns True if newly created."""
    slug = dataset_ref.split("/")[-1]
    meta = {
        "title": slug,
        "id": dataset_ref,
        "licenses": [{"name": "CC0-1.0"}],
    }
    (folder / "dataset-metadata.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")

    exists = False
    try:
        with protect_stdout():
            api.dataset_list_files(dataset_ref)
        exists = True
    except Exception:
        exists = False

    with protect_stdout():
        if exists:
            api.dataset_create_version(
                folder=str(folder),
                version_notes=notes,
                quiet=True,
                convert_to_csv=False,
                dir_mode="skip",
            )
            return False
        api.dataset_create_new(
            folder=str(folder),
            public=False,
            quiet=True,
            convert_to_csv=False,
            dir_mode="skip",
        )
        return True


def build_wheelhouse(
    settings: Settings,
    packages: str | list[str],
    slug: str = "wheels",
    python_version: str = "312",
) -> dict[str, Any]:
    """Download Linux x86_64 binary wheels locally and publish to a private Kaggle Dataset."""
    pkg_list = normalize_str_list(packages)
    if not pkg_list:
        raise ValueError("Provide at least one package name for `kaggle_wheelhouse`.")

    clean_slug = normalize_slot(slug)
    ds_slug = "kgsh-wheels" if clean_slug == "wheels" else f"kgsh-wheels-{clean_slug}"
    ds_ref = f"{settings.kaggle_username}/{ds_slug}"
    py_ver = python_version.replace(".", "").strip() or "312"

    with tempfile.TemporaryDirectory(prefix="kgsh_wheels_") as tmp:
        tmp_p = Path(tmp)
        cmd = [
            sys.executable,
            "-m",
            "pip",
            "download",
            "--dest",
            str(tmp_p),
            "--platform",
            "manylinux2014_x86_64",
            "--platform",
            "manylinux_2_28_x86_64",
            "--python-version",
            py_ver,
            "--implementation",
            "cp",
            "--abi",
            f"cp{py_ver}",
            "--only-binary=:all:",
            *pkg_list,
        ]
        res = subprocess.run(cmd, capture_output=True, text=True, check=False)
        if res.returncode != 0:
            raise RuntimeError(
                f"pip download failed (exit {res.returncode}):\n{(res.stderr or res.stdout)[-1500:]}"
            )

        wheels = sorted(tmp_p.glob("*.whl"))
        total_mb = round(sum(w.stat().st_size for w in wheels) / (1024 * 1024), 2)

        api = get_kaggle_api(settings)
        created = _upsert_private_dataset(api, ds_ref, tmp_p, notes=f"wheels:{','.join(pkg_list)[:60]}")

    return {
        "dataset_ref": ds_ref,
        "created_new": created,
        "python_abi": f"cp{py_ver}-manylinux_x86_64",
        "wheel_count": len(wheels),
        "total_mb": total_mb,
        "wheels": [w.name for w in wheels],
    }


def submit_offline_batch(
    settings: Settings,
    command: str,
    local_path: str = "",
    *,
    slot: str = "batch-1",
    accelerator: str = "NvidiaTeslaT4",
    competition: str | list[str] | None = None,
    enable_internet: bool = False,
    wheel_datasets: str | list[str] | None = None,
    mount_datasets: str | list[str] | None = None,
    mount_models: str | list[str] | None = None,
) -> dict[str, Any]:
    """Bundle local code into a private Dataset and push a batch kernel (supports L4x4 / RTX Pro 6000 offline)."""
    s = normalize_slot(slot)
    acc_spec = resolve_accelerator(accelerator, gpu=True)
    api = get_kaggle_api(settings)

    comp_list = normalize_str_list(competition)
    wheel_ds_list = normalize_str_list(wheel_datasets)
    extra_ds_list = normalize_str_list(mount_datasets)
    model_list = normalize_str_list(mount_models)

    code_ds_slug = ""
    code_ds_ref = ""
    inline_bundle_b64 = ""
    top_entry = ""

    if local_path and local_path.strip():
        src_p = Path(local_path).expanduser().resolve()
        tar_bytes = pack_tar_gz(src_p)
        top_entry = src_p.name if src_p.is_dir() else ""

        if len(tar_bytes) <= 512 * 1024:
            # Embed <=512KB source bundles directly inside the script: 0 dataset lag, 100% atomic!
            inline_bundle_b64 = base64.b64encode(tar_bytes).decode("ascii")
        else:
            # Use .kgsh extension so Kaggle Dataset ingestion never auto-extracts or strips the archive
            code_ds_slug = f"kgsh-code-{s}"
            code_ds_ref = f"{settings.kaggle_username}/{code_ds_slug}"
            with tempfile.TemporaryDirectory(prefix=f"kgsh_code_{s}_") as tmp:
                tmp_p = Path(tmp)
                (tmp_p / "bundle.kgsh").write_bytes(tar_bytes)
                _upsert_private_dataset(api, code_ds_ref, tmp_p, notes=f"batch:{s}")

            # Wait until Kaggle finishes indexing bundle.kgsh before attaching to kernel
            for _ in range(12):
                time.sleep(3.0)
                try:
                    with protect_stdout():
                        flist = api.dataset_list_files(code_ds_ref)
                    fnames = [getattr(f, "name", str(f)) for f in getattr(flist, "files", [])]
                    if any("bundle.kgsh" in fn for fn in fnames):
                        break
                except Exception:
                    continue

    all_datasets: list[str] = []
    for ds in ([code_ds_ref] if code_ds_ref else []) + wheel_ds_list + extra_ds_list:
        if ds and ds not in all_datasets:
            all_datasets.append(ds)

    wheel_slugs = [d.split("/")[-1] for d in wheel_ds_list if d]
    batch_cfg = {
        "command": command,
        "inline_bundle_b64": inline_bundle_b64,
        "code_dataset_slug": code_ds_slug,
        "top_entry": top_entry,
        "wheel_slugs": wheel_slugs,
        "max_lifetime_sec": acc_spec.max_lifetime_sec,
        "drain_at_sec": acc_spec.drain_at_sec,
    }
    b64_cfg = base64.b64encode(json.dumps(batch_cfg).encode("utf-8")).decode("ascii")
    runner_src = OFFLINE_RUNNER_TEMPLATE.replace("__BATCH_CONFIG_B64__", b64_cfg)

    kernel_ref = settings.kernel_ref_for_slot(s, mode="batch")
    kernel_slug = settings.kernel_slug_for_slot(s, mode="batch")
    bundle_dir = STATE_DIR / f"build_batch_{s}"
    bundle_dir.mkdir(parents=True, exist_ok=True)
    (bundle_dir / "offline_runner.py").write_text(runner_src, encoding="utf-8")

    kernel_meta: dict[str, Any] = {
        "id": kernel_ref,
        "title": kernel_slug,
        "code_file": "offline_runner.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": acc_spec.enable_gpu,
        "enable_tpu": acc_spec.enable_tpu,
        "enable_internet": bool(enable_internet),
        "dataset_sources": all_datasets,
        "competition_sources": comp_list,
        "kernel_sources": [],
        "model_sources": model_list,
    }
    if acc_spec.machine_shape:
        kernel_meta["machine_shape"] = acc_spec.machine_shape

    (bundle_dir / "kernel-metadata.json").write_text(
        json.dumps(kernel_meta, indent=2),
        encoding="utf-8",
    )

    with protect_stdout():
        push_resp = api.kernels_push(str(bundle_dir), acc=acc_spec.machine_shape)
    version_number = validate_push_response(push_resp)

    sess = ActiveSession(
        session_id=f"batch_{secrets.token_hex(8)}",
        kernel_ref=kernel_ref,
        created_at=time.time(),
        slot=s,
        mode="batch",
        accelerator=acc_spec.label,
        version_number=version_number,
        competition=",".join(comp_list),
        enable_internet=bool(enable_internet),
    )
    save_active_session(sess, slot=s)

    return {
        "slot": s,
        "mode": "batch",
        "kernel_ref": kernel_ref,
        "version_number": version_number,
        "accelerator": acc_spec.label,
        "enable_internet": bool(enable_internet),
        "code_dataset": code_ds_ref or None,
        "attached_datasets": all_datasets,
        "competition_sources": comp_list,
        "model_sources": model_list,
        "next_step": f"Theo dõi tiến độ & đọc live log qua `kaggle_batch_logs(slot='{s}')`.",
    }


def _extract_event_text(ev: Any) -> str:
    if isinstance(ev, str):
        raw = ev
    elif isinstance(ev, dict):
        raw = str(ev.get("data", ""))
    else:
        raw = str(ev)

    stripped = raw.strip()
    if stripped.startswith("{") and stripped.endswith("}"):
        try:
            parsed = json.loads(stripped)
            if isinstance(parsed, dict) and "data" in parsed:
                return str(parsed["data"])
        except Exception:
            pass
    return raw


def collect_stream_window(
    stream_iter: Any,
    wait_sec: float = 5.0,
    idle_break_sec: float = 1.2,
) -> tuple[str, bool]:
    """Read from a potentially infinite SSE generator for at most `wait_sec` without hanging."""
    q: queue.Queue[tuple[str, Any]] = queue.Queue()
    stop_flag = threading.Event()

    def _reader() -> None:
        try:
            for item in stream_iter:
                if stop_flag.is_set():
                    break
                q.put(("item", item))
            q.put(("eof", None))
        except Exception as exc:
            q.put(("err", exc))

    t = threading.Thread(target=_reader, daemon=True)
    t.start()

    chunks: list[str] = []
    reached_eof = False
    deadline = time.monotonic() + max(0.5, float(wait_sec))

    try:
        while True:
            rem = deadline - time.monotonic()
            if rem <= 0:
                break
            timeout = min(rem, idle_break_sec if chunks else rem)
            try:
                kind, payload = q.get(timeout=max(0.05, timeout))
            except queue.Empty:
                if chunks:
                    break
                continue

            if kind == "eof":
                reached_eof = True
                break
            if kind == "err":
                if not chunks:
                    raise payload
                break
            chunks.append(_extract_event_text(payload))
    finally:
        stop_flag.set()
        close_fn = getattr(stream_iter, "close", None)
        if callable(close_fn):
            try:
                close_fn()
            except Exception:
                pass

    return "".join(chunks), reached_eof


def read_batch_logs_windowed(
    settings: Settings,
    slot: str = "batch-1",
    kernel_ref: str = "",
    tail_lines: int = 100,
    grep: str = "",
    wait_sec: float = 5.0,
) -> dict[str, Any]:
    """Read live or persisted execution logs via Kaggle Host SSE even when enable_internet=false."""
    api = get_kaggle_api(settings)
    s = normalize_slot(slot)
    sess = load_active_session(s)

    if kernel_ref:
        target_ref = kernel_ref.strip()
        versioned_ref = target_ref
    elif sess and sess.kernel_ref:
        target_ref = sess.kernel_ref
        versioned_ref = (
            f"{sess.kernel_ref}/{sess.version_number}" if sess.version_number else sess.kernel_ref
        )
    else:
        target_ref = settings.kernel_ref_for_slot(s, mode="batch")
        versioned_ref = target_ref

    kinfo = get_kernel_status(api, versioned_ref)
    raw_log = ""
    stream_eof = False
    note = ""

    if kinfo["status"] not in {"NOT_CREATED_YET"}:
        try:
            with protect_stdout():
                gen = api.kernels_logs_stream(versioned_ref)
                raw_log, stream_eof = collect_stream_window(gen, wait_sec=wait_sec)
        except Exception as exc:
            note = f"stream_fallback ({exc})"

        if not raw_log and kinfo["status"] in TERMINAL_KERNEL_STATUSES:
            try:
                with protect_stdout():
                    raw_log = api.kernels_logs(versioned_ref) or ""
            except Exception as exc:
                note = f"logs_error ({exc})"

    # Cache cumulative snapshots locally per slot/version so SSE deltas aren't lost across calls
    cache_dir = STATE_DIR / "batch_logs"
    cache_dir.mkdir(parents=True, exist_ok=True)
    safe_name = re.sub(r"[^a-zA-Z0-9_.-]+", "_", versioned_ref)
    cache_file = cache_dir / f"{safe_name}.log"

    if raw_log:
        if stream_eof or kinfo["status"] in TERMINAL_KERNEL_STATUSES:
            cache_file.write_text(raw_log, encoding="utf-8")
        else:
            existing_txt = cache_file.read_text(encoding="utf-8") if cache_file.is_file() else ""
            if raw_log not in existing_txt:
                cache_file.write_text(existing_txt + raw_log, encoding="utf-8")

    full_text = cache_file.read_text(encoding="utf-8") if cache_file.is_file() else raw_log
    cleaned = clean_log_text(full_text)
    lines = cleaned.splitlines()
    if grep:
        pat = re.compile(grep, re.IGNORECASE)
        lines = [ln for ln in lines if pat.search(ln)]
    tail = lines[-max(1, int(tail_lines)) :]

    return {
        "slot": s,
        "kernel_ref": versioned_ref,
        "kaggle_api_status": kinfo["status"],
        "failure_message": kinfo["failure_message"],
        "returned_lines": len(tail),
        "logs": "\n".join(tail),
        **({"note": note} if note else {}),
    }
